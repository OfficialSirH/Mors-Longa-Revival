#!/usr/bin/env python3
"""Build a Teardown 2.x tool prefab for a Mors Longa gun model.

v1 guns registered a placeholder vox and then, from the client, attached the
parts of script/Weapons/<GUN>-<camo>.xml to the tool body (LoadTool). In v2 a
client may not do that, so the parts must be part of the tool itself. A tool
prefab needs the official layout (see mods/minigun/prefab/minigun.xml):
    tool_space -> <body dynamic="false"> -> <vox .../>

The <GUN>-<camo>.xml wrappers instance "<GUN> Base.xml" with offsets that cancel
out (e.g. AK74: group 0.5 -1.5 0.1 + instance -0.5 1.5 -0.1), so the parts sat
exactly at their Base.xml positions. The <vox> lines are copied verbatim and in
order (the gun scripts address parts by index), with the camo vox file swapped in.

Usage (repo root): python3 tools/porting/make_tool_prefab.py AK74 [camo ...]
Writes script/Weapons/<GUN> Tool.xml (default camo) and "<GUN> Tool-<camo>.xml".
"""
import re, sys

W = 'script/Weapons/'

def read(p):
    return open(p, 'rb').read().decode('utf-8').replace('\r\n', '\n')

def build(gun, camo):
    wrapper = read(f'{W}{gun}-{camo}.xml')
    inst = re.search(r'<instance\s+pos="([^"]+)"[^>]*file="MOD/([^"]+)"', wrapper)
    grp = re.search(r'<group\s+pos="([^"]+)"\s+prop0="file=(MOD/[^"]+)"', wrapper)
    assert inst and grp, f'{gun}-{camo}.xml: unexpected wrapper layout'
    a = [float(x) for x in grp.group(1).split()]
    b = [float(x) for x in inst.group(1).split()]
    off = [round(x + y, 4) for x, y in zip(a, b)]
    assert off == [0, 0, 0], f'{gun}-{camo}.xml: wrapper offsets do not cancel: {off}'
    base = read(inst.group(2))
    voxes = re.findall(r'^\s*(<vox [^>]*/>)\s*$', base, re.M)
    assert voxes and len(voxes) == base.count('<vox '), 'Base.xml: every <vox> must be on its own line'
    camo_vox = grp.group(2)
    # Vox file: parts that name the gun's vox get the camo vox; parts without file=
    # inherit it from the wrapper's prop0="file=..." override (TT33, G17, M4, ...).
    base_files = set(re.findall(r'file="([^"]+)"', '\n'.join(voxes)))
    assert len(base_files) <= 1, f'Base.xml uses several vox files: {base_files}'
    base_file = base_files.pop() if base_files else None
    def set_file(v):
        if ' file="' not in v:
            return v.replace('<vox ', f'<vox file="{camo_vox}" ', 1)
        return v.replace(f'file="{base_file}"', f'file="{camo_vox}"')
    voxes = [set_file(v) for v in voxes]
    # Part order. v1 gun scripts address parts as GetBodyShapes(toolBody)[i]. After v1
    # LoadTool, index i was the i-th part counted from the END of Base.xml (GetBodyShapes
    # lists the most recently attached shape first). Checked against the code: AK74 [2]
    # mag = "2" (file lists 65..1), FiveSeven [2] mag = "1-24", [5] suppressor = "1-21"
    # (file lists 1, 1-1..1-25). An engine-built tool numbers parts in file order, so
    # the parts are written in reverse.
    voxes = voxes[::-1]
    # In v2 the tool body is a real body in the world: make the parts unbreakable
    # (gun melee MakeHole at the stock etc.) and tag them so GunRaycast() in
    # script/gunfunctions.lua lets bullets pass through weapon models.
    assert not any(' tags=' in v for v in voxes), 'Base.xml parts already have tags; merge needed'
    voxes = [v.replace('<vox ', '<vox tags="ml_toolpart unbreakable" ', 1) for v in voxes]
    # Parts that overlap inside one body lose their overlapping voxels when the engine
    # builds the tool [verified in-game, AK74]. Build each part in its own lane on a
    # grid; GunNet_FixToolParts() in script/gunnet.lua moves it back on the client
    # (only while |x - lane_x(i)| < SPACING/2). Keep SPACING/COLUMNS in sync.
    SPACING, COLUMNS = 24.0, 10
    def lane(i):
        return ((i - 1) % COLUMNS + 1) * SPACING, ((i - 1) // COLUMNS) * SPACING
    def shift(v, i):
        m = re.search(r'pos="([^"]+)"', v)
        x, y, z = (float(t) for t in m.group(1).split())
        assert abs(x) < SPACING / 2, f'part {i} x={x}: outside +-{SPACING/2} m, lane test would be ambiguous'
        lx, ly = lane(i)
        return v.replace(m.group(0), f'pos="{x + lx:g} {y + ly:g} {z:g}"', 1)
    voxes = [shift(v, i) for i, v in enumerate(voxes, 1)]
    name = f'{gun} Tool.xml' if camo == '' else f'{gun} Tool-{camo}.xml'
    out = (f'<prefab version="1.5.4">\n'
           f'\t<group name="instance=MOD/{W}{name}">\n'
           f'\t\t<!-- Generated by tools/porting/make_tool_prefab.py from {gun}-{camo}.xml; do not edit by hand. -->\n'
           f'\t\t<group name="tool_space">\n'
           f'\t\t\t<body dynamic="false">\n'
           + ''.join(f'\t\t\t\t{v}\n' for v in voxes) +
           f'\t\t\t</body>\n\t\t</group>\n\t</group>\n</prefab>\n')
    open(W + name, 'wb').write(out.replace('\n', '\r\n').encode('utf-8'))
    print(f'{W}{name}: {len(voxes)} parts, vox {camo_vox}')

gun = sys.argv[1]
for camo in [''] + sys.argv[2:]:
    build(gun, camo)
