"""Cut each roadside decor part (prefabs/spawnables/roadsegments/decor/<Segment>_<side>.xml, ~1600 shapes, ~0.2 s
to spawn in one frame, measured 2026-11-17) into chunks of about CHUNK_SHAPES shapes, written to
prefabs/spawnables/roadsegments/decor/chunks/<Segment>_<side>_<n>.xml, and regenerate world/generation/DecorParts.lua
with the chunk paths. GenerateRoad spawns one queue entry per frame, so each chunk gets its own frame.

Placement is kept: every chunk repeats the original wrapper chain (prefab > instance group > decor group > side
group) with the same attributes; only the side group's children are divided, in order and whole (a bush group is
never split). Self-check before writing: the chunks' children joined in order equal the original children, and each
chunk's wrapper attributes equal the original's. The original part files stay (the horde level and the credits
prefab place them directly). Re-runnable: it only reads the original part files.

    python tools/porting/chunk_decor.py [--dry-run]
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DECOR = os.path.join(ROOT, "prefabs", "spawnables", "roadsegments", "decor")
CHUNKS = os.path.join(DECOR, "chunks")
PARTS_LUA = os.path.join(ROOT, "world", "generation", "DecorParts.lua")
CHUNK_SHAPES = 200
SHAPE_TAGS = ("vox", "voxbox", "voxagon")


def shape_count(el):
    return sum(1 for e in el.iter() if e.tag in SHAPE_TAGS)


def split_level(root):
    """The wrapper chain (elements with exactly one child) down to the first element with several children."""
    chain = [root]
    while len(list(chain[-1])) == 1:
        chain.append(list(chain[-1])[0])
    return chain


def build_chunk(chain, children):
    """A copy of the wrapper chain whose last element holds `children`."""
    top = None
    parent = None
    for el in chain:
        if el.tag == "script":   # never start another copy of a wrapper's script (SafeZone fix, 2026-11-17)
            new = ET.Element("group", {k: v for k, v in el.attrib.items() if k in ("pos", "rot")})
        else:
            new = ET.Element(el.tag, dict(el.attrib))
        new.text = el.text
        if parent is None:
            top = new
        else:
            parent.append(new)
        parent = new
    for c in children:
        parent.append(c)
    return top


def text_of(el):
    return ET.tostring(el, encoding="unicode")


def main():
    dry = "--dry-run" in sys.argv
    files = sorted(f for f in os.listdir(DECOR) if f.endswith(".xml"))
    parts = {}
    total_chunks = 0
    for f in files:
        m = re.match(r"(.+)_(left|right)\.xml$", f)
        if not m:
            continue
        segment, side = m.group(1), m.group(2)
        tree = ET.parse(os.path.join(DECOR, f))
        root = tree.getroot()
        chain = split_level(root)
        children = list(chain[-1])
        groups, cur, n = [], [], 0
        for c in children:
            k = shape_count(c)
            if cur and n + k > CHUNK_SHAPES:
                groups.append(cur)
                cur, n = [], 0
            cur.append(c)
            n += k
        if cur:
            groups.append(cur)
        # self-check: children joined in order == original children; wrappers identical
        joined = [text_of(c) for g in groups for c in g]
        assert joined == [text_of(c) for c in children], f
        chunks = [build_chunk(chain, g) for g in groups]
        for ch in chunks:
            a = split_level(ch)
            assert [(e.tag, e.attrib) for e in a[:len(chain)]] == [(e.tag, e.attrib) for e in chain], f
        assert sum(shape_count(ch) for ch in chunks) == shape_count(root), f
        paths = []
        for i, ch in enumerate(chunks, 1):
            name = "%s_%s_%d.xml" % (segment, side, i)
            paths.append("MOD/prefabs/spawnables/roadsegments/decor/chunks/" + name)
            if not dry:
                os.makedirs(CHUNKS, exist_ok=True)
                ET.indent(ch, space="\t")
                with open(os.path.join(CHUNKS, name), "w", encoding="utf-8", newline="\n") as out:
                    out.write(text_of(ch) + "\n")
        parts.setdefault(segment, []).extend(paths)
        total_chunks += len(chunks)
        print("%s: %d shapes -> %d chunks (max %d)" % (f, shape_count(root), len(chunks),
                                                      max(shape_count(ch) for ch in chunks)))
    lines = [
        "-- GENERATED by tools/porting/split_decor.py, chunked by tools/porting/chunk_decor.py (2026-11-17): roadside",
        "-- decor prefabs per road segment, ~%d shapes each, spawned by GenerateRoad.lua one per frame after the segment" % CHUNK_SHAPES,
        "-- (a whole side of ~1600 shapes took ~0.2 s in one frame).",
        "DECOR_PARTS = {",
    ]
    for seg in sorted(parts):
        lines.append('\t["%s"] = { %s },' % (seg, ", ".join('"%s"' % p for p in parts[seg])))
    lines.append("}")
    print("%d parts -> %d chunks" % (len(files), total_chunks))
    if not dry:
        with open(PARTS_LUA, "w", encoding="utf-8", newline="\n") as out:
            out.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
