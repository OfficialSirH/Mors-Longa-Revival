#!/usr/bin/env python3
"""Convert a Mors Longa v1 gun script (script/<GUN>.lua) to a #version 2 script.

All gun "feel" logic stays on the client; world effects go through gunnet.lua.
Fails loudly (AssertionError) when the file deviates from the expected template,
so each gun gets looked at instead of being converted wrongly.
"""
import re, sys

path = sys.argv[1]
raw = open(path, 'rb').read().decode('latin-1')
crlf = False  # (2026-11-08) the repo is LF (.gitattributes); old commits read as input may still be CRLF
s = raw.replace('\r\n', '\n')
notes = []

def sub(pattern, repl, count=None, flags=0, min_count=1):
    """Regex replace; assert on the number of matches."""
    global s
    new, n = re.subn(pattern, repl, s, flags=flags)
    if count is not None:
        assert n == count, f'{pattern!r}: expected {count}, got {n}'
    else:
        assert n >= min_count, f'{pattern!r}: expected >= {min_count}, got {n}'
    s = new
    return n

assert not s.startswith('#version 2'), 'already converted'

# --- tool id / registration -------------------------------------------------
# init() registers the tool somewhere in its body (sometimes after other setup,
# sometimes twice: the last call wins) and usually enables it via the v1 registry.
mi = re.search(r'^function init\(\)\n', s, re.M)
assert mi, 'no function init()'
me = re.search(r'^end\b', s[mi.end():], re.M)
assert me, 'init() has no closing end at column 0'
init_body = s[mi.end():mi.end() + me.start()]
regs = list(re.finditer(r'^(\s*)RegisterTool\(("gun-[^"]+"),\s*("[^"]+"),\s*("[^"]+"),\s*(\d+)\s*\)[ \t]*$', init_body, re.M))
assert regs, 'init() does not call RegisterTool("gun-...", name, file, group)'
last = regs[-1]
tool_id, tool_name, tool_vox, tool_group = last.group(2), last.group(3), last.group(4), last.group(5)
assert all(r.group(2) == tool_id for r in regs), 'init() registers several tool ids'
tid = tool_id.strip('"')
init_body = re.sub(r'^(\s*)RegisterTool\(' + re.escape(tool_id) + r',[^\n]*\)[ \t]*$', r'\1-- (v2) RegisterTool moved to server.init()', init_body, flags=re.M)
am = re.search(r'^\s*Set(?:Float|Int)\("game\.tool\.' + re.escape(tid) + r'\.ammo",\s*([0-9.]+)\)[ \t]*$', init_body, re.M)
init_ammo = am.group(1) if am else None
init_body = re.sub(r'^(\s*)Set(?:Float|Int)\("game\.tool\.' + re.escape(tid) + r'\.ammo",[^\n]*\)[ \t]*$', r'\1-- (v2) tool ammo set per player in server.init()/server.tick()', init_body, flags=re.M)
init_body = re.sub(r'^(\s*)SetBool\("game\.tool\.' + re.escape(tid) + r'\.enabled",\s*true\)[ \t]*$', r'\1-- (v2) tool enabled per player in server.init()/server.tick()', init_body, flags=re.M)
s = s[:mi.end()] + init_body + s[mi.end() + me.start():]

# The weapon model is the gun's tool prefab (66 parts the gun animates by index).
# v1 attached it to the tool body from the client (LoadTool); in v2 that is not
# allowed, so the engine builds it from RegisterTool on every machine.
# Two kinds of gun:
#  * LoadTool guns: placeholder vox + a multi-part prefab attached by LoadTool. In v2
#    the model must be the tool itself: tool prefab generated by
#    tools/porting/make_tool_prefab.py (official tool_space/<body> layout).
#  * vox guns: registered directly with a multi-object .vox (like the official
#    lasergun); the engine builds those itself, keep the file.
# Camo: v1 re-registered the tool with another file; that is server-only and global
# in v2, so only the default model is registered for now.
uses_loadtool = re.search(r'(?<![\w.:-])LoadTool\(b, weaponPrefab\)', s) is not None
if uses_loadtool:
    pm = re.search(r'"MOD/script/Weapons/([^"]+)-"\.\.camo\.\."\.xml"', s)
    assert pm, 'LoadTool gun without a camo weapon prefab ("MOD/script/Weapons/<X>-"..camo..".xml")'
    tool_vox = f'"MOD/script/Weapons/{pm.group(1)} Tool.xml"'
    notes.append('LoadTool gun, model ' + tool_vox + ' (default camo only)')
else:
    notes.append('vox gun, model ' + tool_vox + ' (default camo only)')

# Re-registrations elsewhere (same tool, only used to refresh the vox for camo) are
# server-only: drop them (the one kept goes to server.init()).
mi = re.search(r'^function init\(\)\n', s, re.M)
head, tail = s[:mi.end()], s[mi.end():]
tail, n = re.subn(r'^(\s*)RegisterTool\(' + re.escape(tool_id) + r',[^\n]*\)[ \t]*$', r'\1-- (v2) RegisterTool moved to server.init()', tail, flags=re.M)
s = head + tail
notes.append(f'removed {n} redundant RegisterTool call(s)')

ammo_call = f' SetToolAmmo({tool_id}, {init_ammo}, p)' if init_ammo else ''
server_block = f'''function server.init()
	RegisterTool({tool_id}, {tool_name}, {tool_vox}, {tool_group})
	for p in Players() do SetToolEnabled({tool_id}, true, p){ammo_call} end
	GunNet_ServerInit()
end

function server.tick(dt)
	for p in PlayersAdded() do SetToolEnabled({tool_id}, true, p){ammo_call} end
	GunNet_ServerTick(dt)
end

function client.init()
'''
s = s[:mi.start()] + server_block + s[mi.end():]


# --- includes ---------------------------------------------------------------
sub(r'^#include "gunstats\.lua"\n', '#include "gunstats.lua"\n#include "gunnet.lua"\n', count=1, flags=re.M)
s = '#version 2\n#include "script/include/player.lua"\n' + s

# --- callbacks --------------------------------------------------------------
sub(r'^function tick\(dt\)\n', 'function client.tick(dt)\n\tGunNet_ClientTick(dt)\n', count=1, flags=re.M)
# update(dt) (Deagle, FiveSeven) only reads inventory/attachment state: client side.
sub(r'^function update\(dt\)\n', 'function client.update(dt)\n', min_count=0, flags=re.M)
sub(r'^function draw\(\)\n', 'function client.draw()\n\tif gunWantsInteractive then UiMakeInteractive() gunWantsInteractive = false end\n\tGunNet_DebugParts()\n', count=1, flags=re.M)
# Ui* calls are only valid in client.draw(); the gun requested interactivity from tick.
n = sub(r'\bUiMakeInteractive\(\)', 'gunWantsInteractive = true', min_count=0)
# undo inside client.draw header line
s = s.replace('if gunWantsInteractive then gunWantsInteractive = true gunWantsInteractive = false end',
              'if gunWantsInteractive then UiMakeInteractive() gunWantsInteractive = false end')

# --- v1 registry → v2 functions -------------------------------------------
sub(r'GetBool\("game\.tool\.' + re.escape(tid) + r'\.enabled"\)', f'IsToolEnabled({tool_id})', min_count=0)
sub(r'GetBool\("game\.tool\.(gun-[a-z0-9]+)\.enabled"\)', r'IsToolEnabled("\1")', min_count=0)
sub(r'SetString\("game\.player\.tool",\s*' + re.escape(tool_id) + r'\)', f'GunNet_SetTool({tool_id})', min_count=0)
sub(r'GetString\("game\.player\.tool"\)', 'GetPlayerTool()', min_count=0)
assert '"game.' not in s, 'unhandled game.* registry access: ' + ', '.join(sorted(set(re.findall(r'"game\.[^"]*"', s))))

# v1 GetPlayerTransform(true) meant "with pitch"; in v2 the argument is a playerId.
sub(r'GetPlayerTransform\(true\)', 'GetPlayerTransformWithPitch()', min_count=0)

# Scope look tweak (sight4 etc.): v1 rotated the player every frame with
# SetPlayerTransform/SetPlayerVelocity, which are server-only in v2. Disabled;
# TODO: re-implement with SetToolAllowedZoom(zoom, sensitivity) (client-only).
n = sub(r'^(\s*)SetPlayerTransform\(ppos2, true\)\n\s*SetPlayerVelocity\(pvel\)[ \t]*$',
        r'\1-- (v2) scope look tweak disabled: SetPlayerTransform/SetPlayerVelocity are server-only. TODO: SetToolAllowedZoom', min_count=0, flags=re.M)
notes.append(f'scope look tweaks disabled: {n}')

# --- firing ------------------------------------------------------------------
# The gun's own Shoot() shadows the engine Shoot(); rename it.
sub(r'^function Shoot\(', 'function FireRound(', count=1, flags=re.M)
# The gun's own Shoot() overrides the engine global for the whole script, so every
# unqualified Shoot( call already meant the gun's function: renaming is exact.
sub(r'(?<![\w.:])Shoot\(', 'FireRound(')
assert not re.search(r'(?<![\w.:])Shoot\(', s), 'engine Shoot() called from client code'

# Shot sound paths, so remote players hear the right sound.
gm = re.search(r'^\s*gunsound\s*=\s*LoadSound\("([^"]+)"\)', s, re.M)
assert gm, 'no gunsound = LoadSound(...)'
sm = re.search(r'^\s*suppressedgunsound\s*=\s*LoadSound\("([^"]+)"\)', s, re.M)
gun_snd = gm.group(1)
sup_snd = sm.group(1) if sm else gun_snd

# After the shell is fully set up in FireRound, hand it to gunnet.lua.
# After the shell is fully set up in FireRound (its last line adds the random
# spread: accuracyFactor for rifles, pelletSpread for shotguns, which loop over
# pellets), hand it to gunnet.lua.
fire_hook = (r'\1\2\n'
             r'\1loadedShell.factor = barrelFactordamage or 1\n'
             r'\1loadedShell.active = false -- simulated by gunnet.lua (client visuals + server world)\n'
             f'\\1GunNet_Fire(loadedShell, muzzle == "muzzle1" and "{sup_snd}" or "{gun_snd}", 0.7)\n')
sub(r'^(\t+)(loadedShell\.predictedBulletVelocity = VecAdd\(loadedShell\.predictedBulletVelocity, Vec\(\(math\.random\(\)-0\.5\)\*[^\n]*\))\n',
    fire_hook, count=1, flags=re.M)

# Grenade launcher shell.
n = sub(r'^(\tgrenadeHandler\.shellNum = \(grenadeHandler\.shellNum%#grenadeHandler\.shells\) \+ 1)\n',
        r'\1\n\tloadedShell.active = false -- simulated by gunnet.lua\n\tGunNet_FireGrenade(loadedShell)\n', min_count=0, flags=re.M)
notes.append(f'grenade hooks: {n}')

# Spent casings: spawn on the server so everyone sees them.
n = sub(r'^(\t)casing = Spawn\(("[^"]+"), (Transform\(casingpos, [^\n]*\))\)\n\tSetBodyVelocity\(casing\[1\], direction\)\n',
        r'\1GunNet_SpawnCasing(\2, \3, direction)\n', min_count=0, flags=re.M)
notes.append(f'casing hooks: {n}')

# Weapon model: built by the engine from RegisterTool; start animating its parts
# once the tool body has them.
n = sub(r'^(\t+)LoadTool\(b, weaponPrefab\)[ \t]*\n\t+body = b[ \t]*\n(\t+)local shapes = GetBodyShapes\(b\)[ \t]*\n',
        r'\1body = b\n\1gunToolShapesPending = true\n\1end\n'
        r'\1if gunToolShapesPending and #GetBodyShapes(b) > 8 then\n\1gunToolShapesPending = false\n\2local shapes = GetBodyShapes(b)\n\2GunNet_FixToolParts(shapes)\n',
        min_count=0, flags=re.M)
notes.append(f'tool model hooks: {n}')
assert not re.search(r'(?<![\w.:-])LoadTool\(', re.sub(r'--[^\n]*', '', s.split('function client.init()',1)[1])), 'client-side LoadTool left'

# Melee holes.
n = sub(r'(?<![\w.:])MakeHole\(stockPos, ', 'GunNet_MakeHole(stockPos, ', min_count=0)
notes.append(f'melee holes: {n}')

# --- guns with their own copies of the projectile simulation ------------------
# (PKM: ProjectileOperations + GrenadeOperations, SG553: GrenadeOperations). They
# override gunfunctions.lua, so give them the same world/fx split.
LOCAL_PROLOGUE = """
	-- (v2) world effects on the server (doFx = false), visuals on clients (doWorld = false); see gunnet.lua
	local doWorld = projectile.doWorld ~= false
	local doFx = projectile.doFx ~= false
	if doFx and GunFunctions_LoadSounds then GunFunctions_LoadSounds() end
	local function noop() end
	local PlaySound = doFx and PlaySound or noop
	local SpawnParticle = doFx and SpawnParticle or noop
	local PointLight = doFx and PointLight or noop
	local DrawLine = doFx and DrawLine or noop
	local MakeHole = doWorld and MakeHole or noop
	local Explosion = doWorld and Explosion or noop
	local SpawnFire = doWorld and SpawnFire or noop
	local ApplyBodyImpulse = doWorld and ApplyBodyImpulse or noop
	local Blood_Pop = doWorld and Blood_Pop or noop
	local PaintRGBA = doWorld and PaintRGBA or noop
	local SetFloat = doWorld and SetFloat or noop
	local toolBody = projectile.owner and GetToolBody(projectile.owner) or GetToolBody()
"""
for fn in ('ProjectileOperations', 'GrenadeOperations'):
    hdr = f'function {fn}(projectile)\n'
    if re.search('^' + re.escape(hdr), s, re.M):
        s = re.sub('^' + re.escape(hdr), hdr + LOCAL_PROLOGUE.lstrip('\n'), s, count=1, flags=re.M)
        notes.append(f'local {fn} split')
# their raycasts must skip weapon parts too (GunRaycast in gunfunctions.lua)
n = sub(r'(?<![\w.:])QueryRaycast\(projectile\.pos, dir, VecLength\(VecSub\(point2, projectile\.pos\)\)\)',
        'GunRaycast(projectile.pos, dir, VecLength(VecSub(point2, projectile.pos)), toolBody)', min_count=0)
if n: notes.append(f'local projectile raycasts -> GunRaycast: {n}')

# --- fixes for original-mod bugs (per tool id) --------------------------------
FIXUPS = {
    # copy-paste bug: the sawed-off gated its inventory/mag update on the MP43 being enabled
    'gun-sawedoff': [('IsToolEnabled("gun-mp43")', 'IsToolEnabled("gun-sawedoff")')],
    # (2026-11-12, user-approved) magazines taken out of the gun were named "Simonov-9" while loot magazines are
    # "Simonov-9-Mag", so the two did not stack; every other gun uses one "-Mag" style name
    'gun-pp19': [('name, maxammo = "Simonov-9", ', 'name, maxammo = "Simonov-9-Mag", ')],
}
# all guns: camo is nil when the item string has fewer than 10 attachment fields (e.g. the tutorial's M4A1); the
# "<X>-"..camo..".xml" line (an unused local) then errored on every gun switch (found in-game 2026-11-07)
n = sub(r'"\.\.camo\.\."', '"..(camo or "").."', min_count=0)
if n: notes.append(f'nil camo guarded: {n}')
# all guns: a round without a bullet type (bullettable[ammo] == nil -> Type "nil") made FireRound error on every shot
# (seen in-game 2026-11-07 with unlimited ammo on); fire it as the calibre's default round (GunPerkFor, gunperks.lua)
n = sub(r'local perktable=gunperks\[perk\]\[Type\]', 'local perktable=GunPerkFor(perk, Type)', min_count=0)
if n: notes.append(f'missing bullet type falls back to the calibre default: {n}')
for old, new in FIXUPS.get(tid, []):
    assert s.count(old) >= 1, f'fixup target missing: {old}'
    s = s.replace(old, new)
    notes.append(f'original-mod bug fixed: {old} -> {new}')

# --- final checks -----------------------------------------------------------
SERVER_ONLY = ['MakeHole', 'Explosion', 'SpawnFire', 'Paint', 'PaintRGBA', 'RegisterTool',
               'SetToolEnabled', 'SetToolAmmo', 'SetPlayerTool', 'SetPlayerHealth', 'SetPlayerTransform',
               'SetPlayerVelocity', 'ApplyPlayerDamage', 'DriveVehicle', 'SetPlayerVehicle']
client_part = s.split('function client.init()', 1)[1]
code = re.sub(r'--\[(=*)\[.*?\]\1\]', '', client_part, flags=re.S)
# Projectile simulations are guarded by doWorld/doFx (see above / gunfunctions.lua).
code = re.sub(r'^function (ProjectileOperations|GrenadeOperations)\(projectile\)\n.*?^end\b', '', code, flags=re.S | re.M)
code = re.sub(r'--[^\n]*', '', code)
left = sorted({f for f in SERVER_ONLY if re.search(r'(?<![\w.:])' + f + r'\s*\(', code)})
assert not left, f'server-only calls left in client code: {left}'
if re.search(r'^function (init|tick|update|draw)\(', s, re.M):
    raise AssertionError('v1 callback left')

out = s.replace('\n', '\r\n') if crlf else s
open(path, 'wb').write(out.encode('latin-1'))
print(f'converted {path} (tool {tid}); ' + '; '.join(notes))
